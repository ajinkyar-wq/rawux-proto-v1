import { defineConfig } from "@lovable.dev/vite-tanstack-config";

export default defineConfig({
  // faceWorker is an ES module worker (it uses fetch+eval to load the UMD ONNX runtime).
  vite: { worker: { format: "es" } },
  tanstackStart: {
    // Redirect TanStack Start's bundled server entry to src/server.ts (our SSR error wrapper).
    // nitro/vite builds from this
    server: { entry: "server" },
  },
  // Force-enable Nitro outside Lovable's CI and target Vercel instead of the Cloudflare default.
  // The lovable wrapper otherwise pins Nitro's output to `dist/`, which breaks Vercel's
  // Build Output API auto-detection — we override that so Nitro emits to `.vercel/output/`.
  nitro: {
    preset: "vercel",
    output: {
      dir: ".vercel/output",
      serverDir: ".vercel/output/functions/__server.func",
      publicDir: ".vercel/output/static",
    },
  },
});
